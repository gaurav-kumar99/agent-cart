export const CATEGORIES = ["gaming","coffee","outdoor","fitness","tech","office","kitchen","home"];

export function searchProducts({ query = "", max_price, category } = {}) {
  const words = String(query).toLowerCase().split(/\s+/).filter(Boolean);
  return CATALOG.map((p) => {
    const hay = `${p.name} ${p.category}`.toLowerCase();
    const score = words.reduce((s, w) => s + (hay.includes(w) ? 1 : 0), 0);
    return { p, score };
  })
    .filter(({ p, score }) => (words.length === 0 || score > 0) &&
      (max_price == null || p.price <= max_price) &&
      (!category || p.category === String(category).toLowerCase()))
    .sort((a, b) => b.score - a.score || a.p.price - b.p.price)
    .slice(0, 8)
    .map(({ p }) => p);
}

export function getProduct(id) {
  return CATALOG.find((p) => p.id === id);
}
